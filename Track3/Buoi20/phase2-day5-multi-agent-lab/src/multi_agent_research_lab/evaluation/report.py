"""Benchmark report rendering with analysis section."""

from __future__ import annotations

from multi_agent_research_lab.core.schemas import BenchmarkMetrics


def render_markdown_report(metrics: list[BenchmarkMetrics]) -> str:
    """Render benchmark metrics to a markdown report with summary analysis."""

    lines = [
        "# Benchmark Report — Multi-Agent vs Single-Agent",
        "",
        "## Metrics table",
        "",
        "| Run | Latency (s) | Cost (USD) | Quality /10 | Notes |",
        "|---|---:|---:|---:|---|",
    ]
    for item in metrics:
        cost = "" if item.estimated_cost_usd is None else f"{item.estimated_cost_usd:.6f}"
        quality = "" if item.quality_score is None else f"{item.quality_score:.1f}"
        lines.append(f"| {item.run_name} | {item.latency_seconds:.3f} | {cost} | {quality} | {item.notes} |")

    # Pair-wise analysis: every two consecutive rows assumed baseline vs multi-agent.
    if len(metrics) >= 2:
        lines += ["", "## Per-query analysis", ""]
        for i in range(0, len(metrics) - 1, 2):
            b, m = metrics[i], metrics[i + 1]
            latency_delta = m.latency_seconds - b.latency_seconds
            q_delta = (m.quality_score or 0) - (b.quality_score or 0)
            cost_delta = (m.estimated_cost_usd or 0) - (b.estimated_cost_usd or 0)
            verdict = "multi-agent wins on quality" if q_delta > 0 else "single-agent sufficient"
            lines += [
                f"### {b.run_name.split('|')[-1].strip() if '|' in b.run_name else b.run_name}",
                "",
                f"- Latency delta: {latency_delta:+.3f}s (multi-agent {'slower' if latency_delta > 0 else 'faster'})",
                f"- Quality delta: {q_delta:+.1f}/10",
                f"- Cost delta: ${cost_delta:+.6f}",
                f"- Verdict: {verdict}",
                "",
            ]

    lines += [
        "## Exit ticket",
        "",
        "**When to use multi-agent?**",
        "Tasks with clearly distinct sub-skills (research, analysis, writing), where quality "
        "matters more than latency or cost. The decomposition allows each agent to specialise "
        "and catch mistakes in the previous stage.",
        "",
        "**When NOT to use multi-agent?**",
        "Simple, narrow tasks (FAQ lookup, single-step transforms) where a single LLM call "
        "suffices. The overhead in latency, token cost, and orchestration complexity is not "
        "justified when there is no specialisation benefit.",
        "",
        "---",
        "_Generated by multi-agent-research-lab benchmark CLI._",
    ]
    return "\n".join(lines) + "\n"
